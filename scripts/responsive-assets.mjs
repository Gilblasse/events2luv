import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
// Derive smaller files from the existing optimized collection, never upscale.
const result = {};
for (const name of (await readdir("public/assets")).filter(
  (n) => n.endsWith(".webp") && !/-w\d+\.webp$/.test(n),
)) {
  const source = "public/assets/" + name;
  const { width, height } = await sharp(source).metadata();
  const variants = [];
  for (const size of [480, 800, 1200]) {
    if (size >= width) continue;
    const variant = name.replace(".webp", `-w${size}.webp`);
    await sharp(source)
      .resize({ width: size, withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile("public/assets/" + variant);
    variants.push(`/assets/${variant} ${size}w`);
  }
  variants.push(`/assets/${name} ${width}w`);
  result["/assets/" + name] = { width, height, srcSet: variants.join(", ") };
}
await writeFile(
  "src/responsiveImages.js",
  `// Generated by scripts/responsive-assets.mjs; bundled assets only.\nexport const responsiveImages = ${JSON.stringify(result, null, 2)};\n`,
);
